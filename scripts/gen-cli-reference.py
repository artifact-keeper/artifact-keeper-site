#!/usr/bin/env python3
"""Write src/content/docs/docs/cli/reference.mdx from `ak --help`.

Usage: scripts/gen-cli-reference.py <path to the ak binary>

Run it with the ak build this site documents. The hand-written cli/*.mdx pages
explain the common tasks; this page lists everything.
"""
import os
import re
import subprocess
import sys
import tempfile

OUT = "src/content/docs/docs/cli/reference.mdx"
# On every command. installation.mdx documents them once.
GLOBAL = {"--format", "-q", "--quiet", "--instance", "--no-input", "--ca-cert", "--color", "-h", "--help", "-V", "--version", "--insecure-http"}
HEADER = """---
title: "Command Reference"
description: "Every ak command and its options"
---

{/* Generated by scripts/gen-cli-reference.py from `ak --help`. Don't edit it by hand. */}

Every command in `{version}`. Each one also takes the [global options](/docs/cli/installation/#global-options). Run `ak <command> --help` for the same text in your terminal.

"""


def mdx_escape(text):
    """MDX reads { and < as code, except inside backticks."""
    parts = re.split(r"(`[^`]*`)", text)
    for i in range(0, len(parts), 2):
        parts[i] = parts[i].replace("{", "\\{").replace("<", "\\<")
    return "".join(parts)


def run_help(ak, env, path):
    result = subprocess.run([ak, *path, "--help"], capture_output=True, text=True, env=env, check=True)
    return result.stdout


def sections(text):
    """Split help text into its intro and {heading: lines}."""
    intro, parts, current = [], {}, None
    for line in text.splitlines():
        match = re.fullmatch(r"([A-Z][A-Za-z ]+):\s*(.*)", line) if not line.startswith(" ") else None
        if match and match.group(1) in ("Usage", "Commands", "Arguments", "Options"):
            current = match.group(1)
            parts[current] = [match.group(2)] if match.group(2) else []
        elif current is None:
            intro.append(line)
        elif current != "Usage" and line and not line.startswith(" "):
            current = "Notes"
            parts.setdefault(current, []).append(line)
        else:
            parts[current].append(line)
    return "\n".join(intro).strip(), parts


def strip_global(lines):
    """Drop the global options, and the wrapped lines that belong to them."""
    kept, keep = [], True
    for line in lines:
        match = re.match(r"\s+((?:-\w, )?--?[\w-]+)", line)
        if match and re.match(r"\s+-", line):
            names = re.findall(r"--?[\w-]+", match.group(1))
            keep = not any(name in GLOBAL for name in names)
        if keep:
            kept.append(line)
    return kept


def subcommands(parts):
    names = []
    for line in parts.get("Commands", []):
        match = re.match(r"  (\S+)(?:,|\s|$)", line)
        if match and match.group(1) != "help":
            names.append(match.group(1))
    return names


def walk(ak, env, path, out):
    intro, parts = sections(run_help(ak, env, path))
    if path:
        depth = min(len(path) + 1, 4)
        out.append(f"{'#' * depth} `ak {' '.join(path)}`\n")
        if intro:
            out.append(mdx_escape(intro) + "\n")
        usage = "\n".join(parts.get("Usage", [])).strip()
        body = []
        if usage:
            body.append("Usage: " + usage)
        for heading in ("Arguments", "Options"):
            lines = parts.get(heading, [])
            if heading == "Options":
                lines = strip_global(lines)
            lines = [line for line in lines if line.strip()]
            if lines:
                body.append(heading + ":\n" + "\n".join(lines))
        out.append("```\n" + "\n\n".join(body) + "\n```\n")
    for name in subcommands(parts):
        walk(ak, env, [*path, name], out)


def main():
    ak = sys.argv[1]
    with tempfile.TemporaryDirectory() as home:
        env = {"HOME": home, "AK_CONFIG_DIR": home, "NO_COLOR": "1", "COLUMNS": "100", "PATH": os.environ["PATH"]}
        version = subprocess.run([ak, "--version"], capture_output=True, text=True, env=env, check=True).stdout.strip()
        out = [HEADER.replace("{version}", version)]
        walk(ak, env, [], out)
    with open(OUT, "w") as handle:
        handle.write("\n".join(out))
    print(f"{OUT}: {sum(1 for part in out if part.startswith('#'))} commands")


main()
